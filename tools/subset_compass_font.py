"""Build the Noto Serif SC subset the landing page's compass actually draws.

The full "chinese-simplified" file from @fontsource is 1.5 MB, for about a
hundred characters, and still lacks a few traditional ones the compass uses
(觜, 軫, 鶉...). This script collects every Han character in the compass source,
finds each one across @fontsource's subset files, cuts those glyphs out and
merges them into one small woff2, plus the @font-face rule that loads it.

Run from the repo root after `npm ci` in frontend/, and again whenever the
compass labels change:

    uv run python tools/subset_compass_font.py
"""
import re
import sys
import tempfile
from pathlib import Path

from fontTools import subset
from fontTools.merge import Merger
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parent.parent
SOURCES = ROOT / "frontend/src/three/compass"
FILES = ROOT / "frontend/node_modules/@fontsource/noto-serif-sc/files"
OUT_FONT = ROOT / "frontend/src/assets/fonts/noto-serif-sc-compass-400.woff2"
OUT_CSS = ROOT / "frontend/src/styles/compass-font.css"

HAN = re.compile(r"[〇㐀-䶿一-鿿豈-﫿]")


def used_chars() -> list[str]:
    chars: set[str] = set()
    for path in SOURCES.rglob("*"):
        if path.suffix in {".js", ".ts"} and ".test." not in path.name:
            chars |= set(HAN.findall(path.read_text(encoding="utf-8")))
    return sorted(chars)


def source_fonts() -> list[Path]:
    # The big chinese-simplified file covers most; numbered files hold the rest.
    main = FILES / "noto-serif-sc-chinese-simplified-400-normal.woff2"
    numbered = sorted(FILES.glob("noto-serif-sc-[0-9]*-400-normal.woff2"))
    return [main, *numbered]


def main() -> int:
    wanted = used_chars()
    remaining = {ord(c) for c in wanted}
    pieces: list[TTFont] = []
    for path in source_fonts():
        font = TTFont(path)
        hit = remaining & set(font.getBestCmap())
        if not hit:
            continue
        options = subset.Options()
        options.layout_features = []
        options.name_IDs = ["*"]
        subsetter = subset.Subsetter(options)
        subsetter.populate(unicodes=hit)
        subsetter.subset(font)
        pieces.append(font)
        remaining -= hit

    # Merger reads files, not TTFont objects.
    with tempfile.TemporaryDirectory() as tmp:
        paths = []
        for i, font in enumerate(pieces):
            font.flavor = None
            paths.append(str(Path(tmp) / f"piece{i}.otf"))
            font.save(paths[-1])
        merged = Merger().merge(paths) if len(paths) > 1 else TTFont(paths[0])

    OUT_FONT.parent.mkdir(parents=True, exist_ok=True)
    merged.flavor = "woff2"
    merged.save(OUT_FONT)

    covered = [c for c in wanted if ord(c) not in remaining]
    ranges = ",".join(f"U+{ord(c):04X}" for c in covered)
    OUT_CSS.write_text(
        "/* Generated by tools/subset_compass_font.py — do not edit by hand.\n"
        " * Only the Han characters the compass draws; see the script for why. */\n"
        "@font-face {\n"
        "  font-family: 'Noto Serif SC';\n"
        "  font-style: normal;\n"
        "  font-display: swap;\n"
        "  font-weight: 400;\n"
        "  src: url(../assets/fonts/noto-serif-sc-compass-400.woff2) format('woff2');\n"
        f"  unicode-range: {ranges};\n"
        "}\n",
        encoding="utf-8",
    )

    sys.stdout.reconfigure(encoding="utf-8")
    print(f"{len(covered)}/{len(wanted)} characters, {OUT_FONT.stat().st_size:,} bytes -> {OUT_FONT.relative_to(ROOT)}")
    if remaining:
        print("not in any Noto Serif SC file (browser falls back):", "".join(chr(u) for u in sorted(remaining)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
